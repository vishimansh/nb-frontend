/**
 * Universal Article Finder
 * Searches pre-configured articles, home feed categories, city articles, and search lists.
 */
export function getArticleDataById(id) {
  if (!id) return liveArticleData;

  // 1. Direct match in specialized articles
  if (SPECIALIZED_ARTICLES[id]) {
    return SPECIALIZED_ARTICLES[id];
  }

  // 2. Search Top Stories
  const topStory = homeFeedData.topStories?.find((s) => s.id === id);
  if (topStory) {
    return buildNormalArticleFromCard(topStory);
  }

  // 3. Search Categories in Home Feed
  if (homeFeedData.categories) {
    for (const cat of homeFeedData.categories) {
      const found = cat.articles?.find((a) => a.id === id);
      if (found) {
        return buildNormalArticleFromCard(found, cat.label, undefined, cat.id);
      }
    }
  }

  // 4. Search City Articles
  if (cityNewsData.articles) {
    const cityArt = cityNewsData.articles.find((a) => a.id === id);
    if (cityArt) {
      return buildNormalArticleFromCard(cityArt, cityArt.category || 'शहर', cityArt.cityName || 'भोपाल', 'city');
    }
  }

  // 5. Default Fallback
  const isLive = LIVE_ARTICLE_IDS.has(id);
  return {
    ...liveArticleData,
    id,
    isLive,
  };
}

