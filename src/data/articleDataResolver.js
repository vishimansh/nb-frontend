export const LIVE_ARTICLE_IDS = new Set(['hero-101', 'sn-1', 'live-bhopal-encroachment']);

export function isArticleLive(id, searchParams) {
  if (searchParams) {
    if (searchParams.get('live') === 'true') return true;
    if (searchParams.get('live') === 'false') return false;
    if (searchParams.get('type') === 'normal') return false;
  }
  if (!id) return true; // Default fallback to hero live article
  return LIVE_ARTICLE_IDS.has(id);
}

